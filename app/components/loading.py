"""Wave loading overlay (design loading_B layout on the satellite background).

The three animated sine waves are app/static/waves.svg (generated by
scripts/make_static_svgs.py; inline svg markup is stripped by Streamlit's HTML
sanitiser). It is shown while the cached data loads after sign-in, and its
motion stops for users who prefer reduced motion.
"""

import time

import streamlit as st

from app.components.auth import hero_html

# Keep the overlay up at least this long so it reads as a transition, not a flash.
MIN_SECONDS = 0.9


# MARKUP +++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

def loading_html():
    """Full-screen loading overlay markup.

    Returns
    -------
    str
    """
    return f'''<div class="leap-loading" role="status" aria-live="polite">
      {hero_html()}
      <div class="leap-waves"><img src="app/static/waves.svg" alt="">
        <div class="leap-loading-text">Loading your dashboard…</div></div>
    </div>'''


# RENDER +++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

def show_loading_while(work):
    """Show the overlay, run `work()`, then remove the overlay.

    Parameters
    ----------
    work : callable
        Warms the caches (e.g. loads processed data and forecasts).

    Returns
    -------
    Any
        Whatever `work()` returns. The overlay stays up for at least
        MIN_SECONDS and is always removed, even if `work()` raises.
    """
    holder = st.empty()
    holder.html(loading_html())
    start = time.perf_counter()
    try:
        result = work()
        time.sleep(max(0.0, MIN_SECONDS - (time.perf_counter() - start)))
        return result
    finally:
        holder.empty()
